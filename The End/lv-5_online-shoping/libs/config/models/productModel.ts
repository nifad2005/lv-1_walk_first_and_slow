import { model, models, Schema } from "mongoose";

const productSchema = new Schema({
  name: {
    type: String,
    required: true,
  },
  description: {
    type: String,
    required: true,
  },
  image: {
    type: String,
    required: true,
  },
  price: {
    type: Number,
    required: true,
  }
})

const ProductModel =  models?.ProductModel || model("ProductModel", productSchema);
export default ProductModel;